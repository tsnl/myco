        let mut input = vec![
            user("hi"),
            assistant_tool(None, "bash", serde_json::json!({})),
            tool_results(&["ok"]),
        ];
        let before = wire_tool_ids(&input).unwrap();
        input.push(user("more"));
        input.push(assistant_tool(None, "bash", serde_json::json!({})));
        input.push(tool_results(&["ok"]));
